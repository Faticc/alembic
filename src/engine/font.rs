pub fn text_w(s: &str, scale: i32) -> i32 {
    let n = s.chars().count() as i32;
    if n == 0 {
        0
    } else {
        n * 6 * scale - scale
    }
}

impl Image {
    /// Рисует строку, возвращает x после последнего символа.
    pub fn text(&mut self, x: i32, y: i32, s: &str, scale: i32, color: Color) -> i32 {
        let mut cx = x;
        for ch in s.chars() {
            let up = ch.to_uppercase().next().unwrap_or(ch);
            let g = glyph(up);
            for (row, bits) in g.iter().enumerate() {
                for col in 0..5 {
                    if bits >> (4 - col) & 1 == 1 {
                        self.fill_rect(cx + col * scale, y + row as i32 * scale, scale, scale, color);
                    }
                }
            }
            cx += 6 * scale;
        }
        cx
    }

    /// Текст с тёмной тенью - читается на любом фоне.
    pub fn text_sh(&mut self, x: i32, y: i32, s: &str, scale: i32, color: Color) -> i32 {
        self.text(x + scale, y + scale, s, scale, 0xC010_0E16);
        self.text(x, y, s, scale, color)
    }

    pub fn text_center(&mut self, cx: i32, y: i32, s: &str, scale: i32, color: Color) {
        self.text_sh(cx - text_w(s, scale) / 2, y, s, scale, color);
    }
}
